let current = 'fa';

export function setLang(lang) {
  if (!DICT[lang]) lang = 'fa';
  current = lang;
}
export function getLang() { return current; }
export function getDir() { return LANGS[current].dir; }

/** t('key', {n: 3}) — with {placeholder} interpolation. */
export function t(key, vars) {
  const table = DICT[current] || DICT.fa;
  let s = table[key];
  if (s === undefined) s = DICT.fa[key];
  if (s === undefined) return key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** Apply data-i18n / data-i18n-ph / data-i18n-title to a subtree. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPh)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
